/** Translate application copy only; record text stays unchanged. */
export function workPlanCopy(locale: 'en' | 'es', text: string): string {
  return locale === 'es' ? spanishCopy[text] ?? text : text;
}

/** Unknown server messages use safe localized recovery copy instead of leaking details. */
export function workPlanActionMessage(locale: 'en' | 'es', message: string): string {
  const safeMessage = Object.hasOwn(spanishCopy, message)
    ? message : 'Connection interrupted. Reload before retrying.';
  return workPlanCopy(locale, safeMessage);
}
